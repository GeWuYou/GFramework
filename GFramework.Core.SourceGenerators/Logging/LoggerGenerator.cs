using GFramework.Core.SourceGenerators.Abstractions.Logging;
using GFramework.Core.SourceGenerators.Diagnostics;
using GFramework.SourceGenerators.Common.Constants;
using GFramework.SourceGenerators.Common.Extensions;
using GFramework.SourceGenerators.Common.Generator;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace GFramework.Core.SourceGenerators.Logging;

/// <summary>
///     日志生成器，用于为标注了 <see cref="LogAttribute" /> 的类自动生成一个日志属性。
/// </summary>
/// <remarks>
///     生成契约：日志工厂经由当前实例绑定的架构上下文按需解析并缓存，
///     不读取任何进程级状态。因此标注类型必须能够获得架构上下文——实现
///     <c>IContextAware</c>、派生 <c>ContextAwareBase</c> 或标注
///     <c>[ContextAware]</c>；否则生成器报告诊断并跳过生成。
///     面向 DI 容器的普通服务应直接构造注入 <c>ILogger&lt;T&gt;</c>，不使用本特性。
/// </remarks>
[Generator]
public sealed class LoggerGenerator : TypeAttributeClassGeneratorBase
{
    /// <summary>
    ///     IContextAware 契约的完整元数据名，用于判断标注类型是否具备上下文访问能力。
    /// </summary>
    private const string ContextAwareInterfaceMetadataName =
        $"{PathContests.CoreAbstractionsNamespace}.Rule.IContextAware";

    /// <summary>
    ///     ContextAwareBase 基类的完整元数据名。
    /// </summary>
    private const string ContextAwareBaseMetadataName =
        $"{PathContests.CoreNamespace}.Rule.ContextAwareBase";

    /// <summary>
    ///     ContextAwareAttribute 的完整元数据名。
    /// </summary>
    private const string ContextAwareAttributeMetadataName =
        $"{PathContests.SourceGeneratorsAbstractionsPath}.Rule.ContextAwareAttribute";

    /// <summary>
    ///     获取属性元数据的完整名称，用于标识日志属性的完全限定名
    /// </summary>
    protected override Type AttributeType => typeof(LogAttribute);

    /// <summary>
    ///     用于语法快速筛选
    /// </summary>
    protected override string AttributeShortNameWithoutSuffix => "Log";

    /// <summary>
    ///     判断标注类型是否能够获得架构上下文。
    /// </summary>
    /// <param name="compilation">当前编译。</param>
    /// <param name="symbol">标注 <c>[Log]</c> 的类型。</param>
    /// <returns>类型可访问架构上下文时为 true。</returns>
    private static bool HasContextAccess(Compilation compilation, INamedTypeSymbol symbol)
    {
        var contextAwareInterface = compilation.GetTypeByMetadataName(ContextAwareInterfaceMetadataName);
        var contextAwareBase = compilation.GetTypeByMetadataName(ContextAwareBaseMetadataName);
        var contextAwareAttribute = compilation.GetTypeByMetadataName(ContextAwareAttributeMetadataName);

        // 手写契约：派生自 ContextAwareBase（其自身实现 IContextAware）。
        for (var baseType = symbol.BaseType; baseType != null; baseType = baseType.BaseType)
        {
            if (contextAwareBase != null && SymbolEqualityComparer.Default.Equals(baseType, contextAwareBase))
                return true;
        }

        // 生成契约：显式实现 IContextAware（含 ContextAwareGenerator 生成部分）。
        if (contextAwareInterface != null && symbol.AllInterfaces.Contains(contextAwareInterface))
            return true;

        // 声明契约：同一编译中通过 [ContextAware] 生成上下文实现。
        if (contextAwareAttribute != null)
        {
            foreach (var attribute in symbol.GetAttributes())
            {
                if (SymbolEqualityComparer.Default.Equals(attribute.AttributeClass, contextAwareAttribute))
                    return true;
            }
        }

        return false;
    }

    /// <summary>
    ///     对类进行额外语义校验：无法访问架构上下文的类型直接失败并报告诊断。
    /// </summary>
    protected override bool ValidateSymbol(
        SourceProductionContext context,
        Compilation compilation,
        ClassDeclarationSyntax syntax,
        INamedTypeSymbol symbol,
        AttributeData attr)
    {
        if (HasContextAccess(compilation, symbol))
            return true;

        context.ReportDiagnostic(Diagnostic.Create(
            LoggerGeneratorDiagnostics.ContextAwareRequired,
            syntax.GetLocation(),
            symbol.Name));
        return false;
    }

    /// <summary>
    ///     生成源代码
    /// </summary>
    /// <param name="context">源生产上下文</param>
    /// <param name="compilation">编译对象</param>
    /// <param name="symbol">命名类型符号</param>
    /// <param name="attr">属性数据</param>
    /// <returns>生成的源代码字符串</returns>
    protected override string Generate(
        SourceProductionContext context,
        Compilation compilation,
        INamedTypeSymbol symbol,
        AttributeData attr)
    {
        var ns = symbol.GetNamespace();
        var className = symbol.GetFullClassName();
        var typeKind = symbol.ResolveTypeKind();
        var generics = symbol.ResolveGenerics();
        var logName = attr.GetFirstCtorString(className);
        var fieldName = attr.GetNamedArgument("FieldName", "_log");
        var access = attr.GetNamedArgument("AccessModifier", "private");

        var sb = new System.Text.StringBuilder()
            .AppendLine("// <auto-generated />")
            .AppendLine("#nullable enable")
            .AppendLine()
            .AppendLine("using Microsoft.Extensions.Logging;");

        if (ns is not null)
            sb.AppendLine()
.Append("namespace ").Append(ns).Append(';').AppendLine();

        sb.AppendLine()
            .AppendLine("/// <summary>")
            .AppendLine("/// 为当前分部类型提供自动生成的日志属性。")
            .AppendLine("/// </summary>")
.Append("partial ").Append(typeKind).Append(' ').Append(className).Append(generics.Parameters).AppendLine();

        foreach (var c in generics.Constraints)
            sb.Append("    ").Append(c).AppendLine();

        sb.AppendLine("{")
            .AppendLine("    /// <summary>生成的日志属性底层缓存；首次访问时按当前上下文解析并复用。</summary>")
            .AppendLine("    private ILogger? __gFrameworkLogBacking;")
            .AppendLine()
            .AppendLine("    /// <summary>")
            .AppendLine("    /// 自动生成的日志记录器。")
            .AppendLine("    /// </summary>")
            .AppendLine("    /// <remarks>日志工厂经由当前实例绑定的架构上下文解析；访问未绑定上下文的实例会抛出异常。</remarks>")
            .Append("    ").Append(access).Append(" ILogger ").Append(fieldName)
            .Append(" => __gFrameworkLogBacking ??= ((global::GFramework.Core.Abstractions.Rule.IContextAware)this).GetContext()")
            .Append(".GetService<ILoggerFactory>().CreateLogger(\"").Append(logName).AppendLine("\");")
            .AppendLine("}");

        return sb.ToString();
    }

    /// <summary>
    ///     可以自定义生成文件名
    /// </summary>
    protected override string GetHintName(INamedTypeSymbol symbol)
    {
        return $"{symbol.Name}.Logger.g.cs";
    }
}
